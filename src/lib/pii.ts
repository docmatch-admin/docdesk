/** ตัดข้อมูลส่วนตัวก่อนเก็บเป็นตัวอย่างคำตอบ (PDPA) */
export function scrubPII(text: string): string {
  return text
    // เลขบัตรประชาชน 13 หลัก (มี/ไม่มีขีด)
    .replace(/\b\d[\s-]?\d{4}[\s-]?\d{5}[\s-]?\d{2}[\s-]?\d\b/g, "[เลขบัตร]")
    // อีเมล
    .replace(/[\w.+-]+@[\w-]+\.[\w.]+/g, "[อีเมล]")
    // เบอร์โทรไทย (ยกเว้นเบอร์คลินิก)
    .replace(/(?<!\d)(?!02-?000-?4586|088-?683-?7899)0\d{1,2}[\s-]?\d{3}[\s-]?\d{3,4}(?!\d)/g, "[เบอร์โทร]")
    .replace(/\+66[\s-]?\d{1,2}[\s-]?\d{3}[\s-]?\d{3,4}/g, "[เบอร์โทร]")
    // HN / เลขที่ผู้ป่วย
    .replace(/\bHN[\s:.-]*\d+/gi, "HN [ลบแล้ว]");
}
