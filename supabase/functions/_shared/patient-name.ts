// ค้นคนไข้ด้วยชื่อ (ตาราง patients ของ DocDesk) — ไม่ใช้ Deno/เครือข่าย เทสด้วย node ได้

/** คำนำหน้าที่ตัดทิ้งก่อนค้น (ในทะเบียนอาจติดกับชื่อ เช่น นายสมชาย) */
export const NAME_TITLES = /^(นางสาว|นาง|นาย|น\.ส\.|ด\.ช\.|ด\.ญ\.|เด็กชาย|เด็กหญิง|คุณ|mr\.?|mrs\.?|ms\.?|miss)\s*/i;

/**
 * คำค้นชื่อ → คำย่อย (ทุกคำต้องเจอในชื่อ): "นาย สมชาย ใจดี" → ["สมชาย", "ใจดี"] · "ใจดี" → ["ใจดี"]
 * ตัดคำนำหน้า และอักขระที่มีความหมายพิเศษใน filter (% , ( ) * \ _)
 */
export function nameSearchTerms(q: string): string[] {
  const clean = q.replace(/[%,()*\\_]/g, " ").trim();
  // คำนำหน้าเฉพาะคำแรก (ทั้งแบบแยก "นาย สมชาย" และแบบติด "นายสมชาย")
  return clean.split(/\s+/)
    .map((w, i) => (i === 0 ? w.replace(NAME_TITLES, "") : w).trim())
    .filter((w) => w.length >= 2)
    .slice(0, 4);
}
