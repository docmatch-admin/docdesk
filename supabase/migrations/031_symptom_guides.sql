-- แนวทางซักอาการ: ร่างต้องให้แพทย์อนุมัติก่อน AI ใช้
alter table knowledge_items add column if not exists review_status text not null default 'approved';
alter table knowledge_items drop constraint if exists knowledge_items_review_status_check;
alter table knowledge_items add constraint knowledge_items_review_status_check check (review_status in ('draft', 'approved'));
alter table knowledge_items add column if not exists reviewed_by uuid references staff(id) on delete set null;
alter table knowledge_items add column if not exists reviewed_at timestamptz;

-- ร่างไม่ถูกค้นเจอ AI จึงไม่เห็น
create or replace function match_knowledge(query_embedding vector(1536), match_count int default 5)
returns table (id uuid, category text, title text, content text, updated_at timestamptz, similarity float)
language sql stable as $$
  select k.id, k.category, k.title, k.content, k.updated_at,
         1 - (k.embedding <=> query_embedding) as similarity
  from knowledge_items k
  where k.active and k.review_status = 'approved' and k.embedding is not null
  order by k.embedding <=> query_embedding
  limit match_count;
$$;

